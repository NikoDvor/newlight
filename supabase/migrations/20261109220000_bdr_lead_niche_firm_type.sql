-- Dialer niche = firm type: RIA, Hybrid, Advisor (broker-dealer), Insurance.
-- Replaces the SEC Form ADV "focus" labels set earlier today (Wealth/Portfolio Management were services, not niches).
create table if not exists public.nl_firm_types (
  crd text primary key,
  firm_type text not null check (firm_type in ('ria', 'hybrid', 'bd', 'insurance')),
  source text not null default 'manual',
  updated_at timestamptz not null default now()
);
alter table public.nl_firm_types enable row level security;
drop policy if exists "nl_firm_types read" on public.nl_firm_types;
create policy "nl_firm_types read" on public.nl_firm_types for select to authenticated using (true);

create or replace function public.nl_niche_label(_t text)
returns text language sql immutable as $$
  select case lower(_t) when 'ria' then 'RIA' when 'hybrid' then 'Hybrid'
    when 'bd' then 'Advisor' when 'ibd' then 'Advisor' when 'insurance' then 'Insurance' else null end
$$;

-- Firm type for a lead: insurance licensing source > AdvizorPro firm type (cache) > lead pool firm > SEC adviser file (RIA).
create or replace function public.nl_bdr_lead_firm_niche(_crd text, _pool uuid, _source text)
returns text language sql stable security definer set search_path = public as $$
  select coalesce(
    case when _source ilike '%insurance%' then 'Insurance' end,
    (select nl_niche_label(t.firm_type) from nl_firm_types t where t.crd = _crd),
    (select nl_niche_label(p.firm_type) from nl_lead_pool_firms p where p.id = _pool),
    (select nl_niche_label(p.firm_type) from nl_lead_pool_firms p where _crd is not null and p.crd = _crd limit 1),
    (select 'RIA' from sec_adv_services s where _crd is not null and s.crd = _crd limit 1)
  )
$$;

create or replace function public.nl_bdr_lead_fill_niche()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if coalesce(trim(new.niche), '') = '' then
    new.niche := nl_bdr_lead_firm_niche(new.crd, new.pool_firm_id, new.lead_source);
  end if;
  return new;
end $$;

drop trigger if exists nl_bdr_lead_fill_niche on public.nl_bdr_leads;
create trigger nl_bdr_lead_fill_niche before insert or update of crd, niche, pool_firm_id on public.nl_bdr_leads
for each row execute function public.nl_bdr_lead_fill_niche();

